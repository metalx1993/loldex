'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const engine=require('../site/search-engine.js');
const vectors=JSON.parse(fs.readFileSync(path.join(__dirname,'test_advanced_search_vectors.json'),'utf8'));
for(const test of vectors.cases){const result=engine.search(test.entries||vectors.entries,test.query,{limit:500});assert.deepEqual(result.results.map(x=>x.entry.id),test.ids,test.query);}
for(const test of vectors.score_cases)assert.equal(engine.search([test.entry],test.query).results[0].score,test.score,test.query);
for(const query of vectors.errors)assert.throws(()=>engine.parse(query),engine.QueryError,query);
assert.throws(()=>engine.parse('a'.repeat(4097)),engine.QueryError);
assert.throws(()=>engine.parse(Array(130).fill('x').join(' ')),engine.QueryError);
assert.throws(()=>engine.parse('('.repeat(17)+'a'+')'.repeat(17)),engine.QueryError);
assert.throws(()=>engine.parse(Array(7).fill('(a OR b)').join(' AND ')),engine.QueryError);
assert.throws(()=>engine.search([], '',{limit:0}),engine.QueryError);
assert.throws(()=>engine.search([], '',{offset:-1}),engine.QueryError);
const a=vectors.entries.find(x=>x.id==='a');
const match=engine.search([a],'capability:A confidence:low');
assert(match.results[0].reasons.some(r=>r.claim?.value==='A'&&r.claim.confidence.level==='low'));
assert(!match.results[0].reasons.some(r=>r.claim?.value==='B'));
assert.deepEqual(engine.search([a],'capability:A').facets.confidence,[{value:'low',count:1}]);
assert.deepEqual(engine.search(vectors.entries,'',{offset:1,limit:1}).results.map(x=>x.entry.id),['b']);
assert.deepEqual(engine.search(vectors.entries.slice().reverse(),'').results.map(x=>x.entry.id),['a','b','c','d']);
assert.deepEqual(engine.search([{id:'\u{10000}'},{id:'\uE000'}],'').results.map(x=>x.entry.id),['\uE000','\u{10000}']);
const cross=JSON.parse(JSON.stringify(a));cross.sources.push({project:'Two'});
assert.equal(engine.search([cross],'source:Two confidence:high').total,0);
assert.equal(engine.search([cross],'source:Two capability:A').total,0);
assert.equal(engine.search([cross],'source:Two claim-exclusive').total,0);
assert.equal(engine.search([cross],'source:Two Alpha').total,1);
assert.equal(engine.search([{id:'bare',sources:[{project:'Two'}]}],'source:Two').total,1);
assert.equal(engine.search([cross],'source:One confidence:high').total,1);
assert.equal(engine.search([a],'capability:A confidence:low confidence:high').total,0);
assert.equal(engine.search([a],'capability:A phase:discovery confidence:high').total,0);
assert.equal(engine.search([a],'capability:A confidence:low OR capability:B confidence:high').total,1);
assert(engine.search([a],'Alpha confidence:high').results[0].reasons.filter(r=>r.field==='name').every(r=>!r.claim&&!r.confidence));
const rank={id:'rank',name:'X',capabilities:['discovery'],phases:['discovery'],claims:{capabilities:[{value:'discovery',confidence:{level:'low'},provenance:{type:'adapter',source:'One'}}],phases:[{value:'discovery',confidence:{level:'high'},provenance:{type:'adapter',source:'One'}}]}};
assert.equal(engine.search([rank],'discovery confidence:high').results[0].score,55);
let bounded='a';for(let i=0;i<3;i++)bounded='NOT ((a OR b OR c OR d OR e OR f) AND '+bounded+')';
let reads=0;engine.evaluate({id:'x',get name(){reads++;return 'a b c d e f';}},engine.parse(bounded));assert(reads<100,'shared opaque subtrees must be evaluated once per entry, not once per parent alternative');
const snapshot=JSON.stringify(vectors.entries);engine.search(vectors.entries,'A OR NOT confidence:verified');assert.equal(JSON.stringify(vectors.entries),snapshot);
const actual=JSON.parse(fs.readFileSync(path.join(__dirname,'../site/catalog.json'),'utf8')).entries;
const start=Date.now();const live=engine.search(actual,'platform:windows confidence:high');
assert(live.total>0);
assert(live.results.every(x=>x.reasons.some(r=>r.claim?.confidence?.level==='high')));
console.log(`${vectors.cases.length} shared vectors; bounds, evidence, facets, ordering, purity PASS; real corpus ${actual.length} search ${Date.now()-start}ms (${live.total} matches)`);
